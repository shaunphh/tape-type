// Gathers what the family board (public/board) draws with, so it ships with Tape Type on GitHub
// Pages at /tape-type/board/:
// - public/board/tape.js: the tape geometry, bundled the way the event guide and the site take it
//   (src/geometry.ts and settings.ts, with the tokens they read);
// - public/board/ad-tokens.json: the shared tokens, copied from src;
// - the variable Barlow GX at its Normal width (src/assets) and its Condensed width (the event
//   guide's instance), the marks (src/assets, and the event guide's Dublin mark), and Guide Studio's
//   four sample photos. Those from the other repos are copied when the repo is here, and the copies
//   already in public/board are kept otherwise (on CI, say), so the board always builds.
//
//   node scripts/board-sync.mjs            # runs before every build (package.json)
//   EVENT_GUIDE_REPO=… GUIDE_STUDIO_REPO=… node scripts/board-sync.mjs
import { execFileSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const board = join(root, 'public', 'board')
for (const dir of ['fonts', 'marks', 'photos']) mkdirSync(join(board, dir), { recursive: true })

// The geometry, bundled with what it reads, from the working tree (the tokens it embeds are this checkout's).
const entry = join(root, 'scripts', '.board-entry.ts')
writeFileSync(entry, "export { buildShape } from '../src/geometry'\nexport { defaults } from '../src/settings'\n")
try {
  execFileSync(join(root, 'node_modules', '.bin', 'esbuild'), [entry, '--bundle', '--format=esm', '--target=es2020', '--legal-comments=none', '--banner:js=// Generated by scripts/board-sync.mjs from src/geometry.ts and settings.ts. Do not edit by hand.', `--outfile=${join(board, 'tape.js')}`], { stdio: 'inherit' })
} finally {
  try { execFileSync('rm', ['-f', entry]) } catch { /* a leftover entry file is harmless */ }
}
copyFileSync(join(root, 'src', 'ad-tokens.json'), join(board, 'ad-tokens.json'))
copyFileSync(join(root, 'src', 'assets', 'fonts', 'BarlowGX-Normal.ttf'), join(board, 'fonts', 'BarlowGX-Normal.ttf'))
for (const mark of ['logo-left.svg', 'logo-right.svg', 'swipe-arrow.svg']) copyFileSync(join(root, 'src', 'assets', mark), join(board, 'marks', mark))

const eventGuide = process.env.EVENT_GUIDE_REPO ?? join(homedir(), 'event-guide')
if (existsSync(join(eventGuide, 'assets', 'fonts', 'BarlowGX-Condensed.ttf'))) {
  copyFileSync(join(eventGuide, 'assets', 'fonts', 'BarlowGX-Condensed.ttf'), join(board, 'fonts', 'BarlowGX-Condensed.ttf'))
  copyFileSync(join(eventGuide, 'assets', 'DublinEventGuide.svg'), join(board, 'marks', 'dublin.svg'))
} else console.log(`No event guide at ${eventGuide}: keeping the Condensed font and Dublin mark already in public/board.`)

const guideStudio = process.env.GUIDE_STUDIO_REPO ?? join(homedir(), 'paper', 'team-events-ireland', 'prototypes', 'guide-studio')
if (existsSync(join(guideStudio, 'public', 'photos'))) {
  for (const file of readdirSync(join(guideStudio, 'public', 'photos')).filter((f) => f.endsWith('.jpg'))) copyFileSync(join(guideStudio, 'public', 'photos', file), join(board, 'photos', file))
} else console.log(`No Guide Studio at ${guideStudio}: keeping the sample photos already in public/board.`)

console.log('public/board: tape.js, ad-tokens.json, fonts, marks and photos are in step.')
